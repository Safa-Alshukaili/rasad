// تصنيف مجاني بالكلمات المفتاحية — بديل لا يحتاج أي API خارجي أو فلوس.
// يفحص نص البلاغ ويبحث عن كلمات دالة على كل تصنيف، ويختار التصنيف
// اللي عنده أكبر عدد تطابقات. هذا منطق بسيط لكنه فعّال لحالات واضحة،
// وهو نفس الأسلوب اللي تستخدمه كثير من الأنظمة الحكومية الحقيقية
// قبل الانتقال لذكاء اصطناعي متقدم.

// كل تصنيف له قائمة كلمات مفتاحية (عربي + بعض الكلمات الشائعة بالإنجليزي)
const KEYWORD_MAP = {
  roads: [
    "حفرة", "حفر", "طريق", "شارع", "رصف", "اسفلت", "أسفلت",
    "حادث", "إشارة", "اشارة", "مرور", "جسر", "كسر الطريق",
    "تشقق", "حواجز", "دوار",
  ],
  water: [
    "مياه", "مياة", "ماء", "تسريب", "تسرب", "أنبوب", "انبوب", "صرف صحي",
    "مجاري", "انقطاع المياه", "انقطعت المياه", "انقطعت", "قطع المياه",
    "خزان", "تلوث المياه", "كسر بالأنبوب", "شبكة المياه", "تسليك",
  ],
  electricity: [
    "كهرباء", "عمود","أعمده","اعمده", "أعمدة", "انقطاع التيار", "كهربائي",
    "كابل", "محول", "صعق", "سلك", "شبكه كهربائيه", "شبكة كهربائية", "إنارة", "اناره",
    "اعمده",
  ],
  waste: [
    "نفايات", "قمامة", "زبالة", "حاوية", "نظافة", "روائح",
    "مكب", "تنظيف", "حشرات", "قوارض", "مخلفات",
  ],
};

/**
 * يحسب عدد الكلمات المتطابقة من كل تصنيف داخل نص البلاغ.
 * يرجع التصنيف الأعلى تطابقاً، أو "other" لو لم يتطابق شيء.
 */
function classifyByKeywords(description) {
  const text = (description || "").toLowerCase();

  let bestCategory = "other";
  let bestScore = 0;
  const scores = {};

  for (const [category, keywords] of Object.entries(KEYWORD_MAP)) {
    let score = 0;
    for (const word of keywords) {
      if (text.includes(word.toLowerCase())) score += 1;
    }
    scores[category] = score;
    if (score > bestScore) {
      bestScore = score;
      bestCategory = category;
    }
  }

  // الثقة هنا مبسّطة: كل ما زادت الكلمات المتطابقة، زادت الثقة، بحد أقصى 0.9
  // (نتركها أقل من 1 دوماً لأنها تخمين بالكلمات وليست فهم لغوي حقيقي)
  const confidence = bestScore === 0 ? 0 : Math.min(0.9, 0.5 + bestScore * 0.15);

  return {
    category: bestScore === 0 ? "other" : bestCategory,
    confidence,
    method: "keywords", // نوضح دوماً الطريقة المستخدمة لأي تصنيف لاحق
  };
}

module.exports = { classifyByKeywords, KEYWORD_MAP };